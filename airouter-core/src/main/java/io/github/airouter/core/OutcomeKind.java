package io.github.airouter.core;

/**
 * 一次调用最终被判定成什么（ADR-0005 第 2 节）。
 *
 * <p>这四类之间是**互斥且穷尽**的：熔断、限流回放、健康检查、指标、配额结算
 * 全部只按这里的取值分支，不得自行从状态码或异常再推一次结论 ——
 * 那正是来源项目「流式恒为成功」的成因。
 */
public enum OutcomeKind {

  /** 正常结束：流式收到了 Terminal，非流式拿到了可用的响应。 */
  SUCCESS,

  /** 上游给出了非 2xx 或非法内容。它归因到上游，计入熔断。 */
  UPSTREAM_FAILURE,

  /** 上游在约定的时间内没有把话说完。它归因到上游，计入熔断。 */
  UPSTREAM_TIMEOUT,

  /**
   * 调用方中途断开。它**不计入熔断**：移动端切后台、用户关页面都会产生取消，
   * 把它算作上游失败会让一次共享网络的抖动熔断掉一个健康的实例。
   *
   * <p>它只在流式路径上产生，而且**不对应任何事件**：取消发生时下游已经不在了，
   * 没有接收方的事件无从投递。但结算仍然要有它 ——
   * 「少记一次」与「记成成功」对下游的熔断器是同一种误导，
   * 而取消恰恰是唯一一种「上游是健康的」的失败形态。
   */
  CLIENT_CANCELLED
}
