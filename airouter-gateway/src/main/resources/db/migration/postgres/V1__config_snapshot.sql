-- V1：配置版本快照（PostgreSQL 方言）
--
-- 与 ../h2/V1__config_snapshot.sql 同名成对，列与约束一一对应，
-- 唯一的差异是正文的类型：PG 用 TEXT（H2 那边用 CLOB）。
-- 两份文件必须一起评审 —— 只在 PG 上验过的 SQL 不算数（ADR-0017 第 1 节），
-- 而默认档位跑的是 H2，所以这一份改了，那一份也要跟着改。
--
-- 消费方与「为什么现在只建这一张表」见 H2 那份文件的头注释，这里不重复。
--
-- 已发布的迁移不可再改（Flyway 按校验和判定）：schema 变更一律新增 V2__ 增量脚本。
create table config_snapshot (
    id bigint generated by default as identity primary key,
    version bigint not null,
    content text not null,
    created_at timestamp(6) not null,
    actor varchar(64) not null,
    constraint uq_config_snapshot_version unique (version)
);
