package io.github.airouter.core;

/**
 * 结算的**唯一**收口点（ADR-0005 第 2 节）。
 *
 * <p>熔断器、延迟样本、指标、配额结算、调用历史全部只从这里取结果，
 * **不得各自观测**：读状态码、读异常类型、或者自己造一个 {@code Outcome}，
 * 都会让「一次调用是成功还是失败」变成取决于谁在问的问题 ——
 * 那正是来源项目「流式恒为成功」的成因。
 *
 * <p>结算发生在**收到终态的那一刻**，不是响应头写出的那一刻：
 * 两者之间隔着整条响应体，而一个持续吐出半截响应的上游，
 * 在「响应头写出即成功」的口径里是 100% 成功。
 *
 * <p>四类 {@link OutcomeKind} 都从这里经过，包括**取消** ——
 * 取消不产生事件（接收方已经不在了），但必须留下一笔，
 * 否则「少记一次」与「记成成功」对熔断器是同一种误导。
 */
public interface OutcomeObserver {

  /**
   * 一笔结算。
   *
   * <p>实现必须是**非阻塞**的：结算发生在流式路径的关键帧上，
   * 在这里做 IO（包括落库）会把一次模型调用的延迟压到每一个调用方头上。
   * 需要持久化的消费者自己去排队，不在这里等。
   *
   * @param outcome 这一次调用的结算结果
   */
  void settle(Outcome outcome);
}
