/**
 * **实例选择**：一次请求打给同一个 Service 下的哪一个实例（ADR-0011）。
 *
 * <p>这个包里全是**纯函数**。它们只看传进来的候选与上下文，不做 IO、不读时钟之外的环境、
 * 也看不到 HTTP 状态码 —— 最后一条由结构规则 R4 判红，而不是靠约定。
 * 纯是为了可确定性断言：给定候选与随机源，结果可复现，
 * 于是「策略对不对」不需要起一个端点，也不需要等一次网络往返。
 *
 * <p>选择是**六步**，写在一处（{@link io.github.airouter.gateway.routing.SelectionChain}）：
 *
 * <ol>
 *   <li>**① 调用方标识** —— 由 {@link io.github.airouter.gateway.routing.SelectionContext}
 *       带进来（阶段 6 的认证填它）。链不解析它，只把它当作参数往后传
 *   <li>**② 目标与标签** —— 规则引擎（阶段 8）决定要哪些标签，链按它筛候选；
 *       一个都不剩就**拒绝**，不退化为「不筛」
 *   <li>**③ 可用性闸门** —— 熔断与限流（阶段 7）在这里把候选筛掉；本阶段恒开
 *   <li>**④ 加权展开** —— 独立的一步（ADR-0011 第 2 节 (b)），不是每个策略各写一遍
 *   <li>**⑤ 粘滞** —— 包装在策略之外（阶段 4 的下一张票）
 *   <li>**⑥ 策略** —— 六个纯函数之一，只看 ④ 的产物与上下文
 * </ol>
 *
 * <p>候选是 {@link io.github.airouter.gateway.routing.Candidate} 而不是注册表里的实例：
 * 这一层因此不认识「实例是怎么出网的」，也不需要一个能出网的对象才能被测试 ——
 * 判「选择对不对」与判「出网对不对」是两件事，混在一起就都要起端点。
 */
