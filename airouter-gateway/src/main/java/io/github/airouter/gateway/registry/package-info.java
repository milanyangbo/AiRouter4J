/**
 * 注册表：**配置 → 运行时对象**的唯一持有者。
 *
 * <p>本包知道的东西：服务 / 实例这两个名字，以及挂在实例上的出站能力。
 * 它不知道请求长什么样，也不参与挑实例 —— 那是 {@code routing} 与 {@code select} 的事。
 *
 * <p>这里必须知道 {@code providers} 与 {@code config}：前者因为它要持有每实例一个的出站能力，
 * 后者因为配置的就是它要登记的那些东西。反过来（{@code providers} 或 {@code config}
 * 回头来找注册表）会让「谁先把谁装配起来」变成一个运行期问题。
 *
 * <p>每实例状态分两类，各住一处、不互相缓存（票 13 裁决，2026-10-30，与
 * {@code GLOSSARY.md}「注册表」条和 ADR-0010 第 2 节说的是同一句）：
 *
 * <ul>
 *   <li>**配置派生的**（熔断状态、健康登记，阶段 7）长在这里：它们随实例对象被替换，
 *       热重载换对象时要带着走
 *   <li>**观测到的**不在这里：延迟样本住 {@code observe}（由 {@code OutcomeObserver} 喂养）、
 *       在途计数住 {@code transport}（在出网口记账）。它们是独立的长生命周期 bean，
 *       配置替换对它们不可见 —— 让注册表也持一份，热重载反而要操心搬移，
 *       原先的热重载论证恰好用反了
 * </ul>
 */
