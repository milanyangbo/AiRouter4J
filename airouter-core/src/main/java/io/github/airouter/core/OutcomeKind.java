package io.github.airouter.core;

/**
 * 一次调用最终被判定成什么（ADR-0006 第 2 节）。
 *
 * <p>这四类之间是**互斥且穷尽**的：熔断器、限流回放、健康检查、指标、配额结算
 * 全部只按这里的取值分支，不得自行从状态码或异常再推一次结论 ——
 * 那正是来源项目「流式恒为成功」的成因。
 */
public enum OutcomeKind {

  /** 正常结束：流式收到了 Terminal，非流式拿到了可用的响应。 */
  SUCCESS,

  /** 上游给出了非 2xx 或非法内容。它归因到上游，计入熔断。 */
  UPSTREAM_FAILURE,

  /** 上游在约定的时间内没有把话说完。它归因到上游，计入熔断。 */
  UPSTREAM_TIMEOUT,

  /**
   * 调用方中途断开。它**不计入熔断**：移动端切后台、用户关页面都会产生取消，
   * 把它算作上游失败会让一次共享网络的抖动熔断掉一个健康的实例。
   *
   * <p>现阶段还没有产生者：取消的观测要等流式出站那一侧把取消信号接进来。
   * 这里先把它列全，是为了让「第三类终态存在」这件事在类型上可见，
   * 而不是等有人需要区分时才发现枚举里没有它的位置。
   */
  CLIENT_CANCELLED
}
