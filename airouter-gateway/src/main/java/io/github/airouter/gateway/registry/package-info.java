/**
 * 注册表：**配置 → 运行时对象**的唯一持有者。
 *
 * <p>本包知道的东西：服务 / 实例这两个名字，以及挂在实例上的出站能力。
 * 它不知道请求长什么样，也不参与挑实例 —— 那是 {@code routing} 与 {@code select} 的事。
 *
 * <p>这里必须知道 {@code providers} 与 {@code config}：前者因为它要持有每实例一个的出站能力，
 * 后者因为配置的就是它要登记的那些东西。反过来（{@code providers} 或 {@code config}
 * 回头来找注册表）会让「谁先把谁装配起来」变成一个运行期问题。
 *
 * <p>后续长到这里的东西：熔断状态、延迟样本、健康登记。它们都附着在同一个实例对象上，
 * 而不是各自存一份映射 —— 一旦有两处持有，热重载必然漏改一处。
 */
